def apply_class_specific_augmentation(img_path, label, num_augmentations, base_seed):
    """
    根据类别应用不同的增强策略
    """
    with Image.open(img_path) as image:
        if image.mode != 'RGB':
            image = image.convert('RGB')

        augmented_images = []

        for aug_idx in range(num_augmentations):
            # 为每个增强创建确定性种子
            rng = random.Random(base_seed + aug_idx * 1000)

            # 基础变换
            img = image.copy()

            # 根据类别应用不同的增强强度
            if label == 1:  # ADHD hyperactive (最重要)
                # 最强的增强：多种变换组合
                # 1. 随机旋转 (-30度到30度)
                if rng.random() > 0.5:
                    angle = rng.uniform(-30, 30)
                    img = img.rotate(angle, resample=Image.BILINEAR, expand=False)

                # 2. 随机翻转
                if rng.random() > 0.5:
                    img = img.transpose(Image.FLIP_LEFT_RIGHT)
                if rng.random() > 0.5:
                    img = img.transpose(Image.FLIP_TOP_BOTTOM)

                # 3. 颜色增强（更强的变化）
                brightness_factor = rng.uniform(0.7, 1.3)
                enhancer = ImageEnhance.Brightness(img)
                img = enhancer.enhance(brightness_factor)

                contrast_factor = rng.uniform(0.7, 1.3)
                enhancer = ImageEnhance.Contrast(img)
                img = enhancer.enhance(contrast_factor)

                sharpness_factor = rng.uniform(0.7, 1.3)
                enhancer = ImageEnhance.Sharpness(img)
                img = enhancer.enhance(sharpness_factor)

                # 4. 颜色平衡调整
                color_factor = rng.uniform(0.8, 1.2)
                enhancer = ImageEnhance.Color(img)
                img = enhancer.enhance(color_factor)

            elif label == 0:  # ADHD combined
                # 中等强度的增强
                if rng.random() > 0.5:
                    img = img.transpose(Image.FLIP_LEFT_RIGHT)

                brightness_factor = rng.uniform(0.8, 1.2)
                enhancer = ImageEnhance.Brightness(img)
                img = enhancer.enhance(brightness_factor)

                contrast_factor = rng.uniform(0.8, 1.2)
                enhancer = ImageEnhance.Contrast(img)
                img = enhancer.enhance(contrast_factor)

            elif label == 2:  # ADHD inattentive
                # 中等强度，类似ADHD combined
                if rng.random() > 0.5:
                    img = img.transpose(Image.FLIP_LEFT_RIGHT)

                brightness_factor = rng.uniform(0.85, 1.15)
                enhancer = ImageEnhance.Brightness(img)
                img = enhancer.enhance(brightness_factor)

            elif label == 3:  # ASD
                # 轻微增强，保持特征
                if rng.random() > 0.7:  # 30%概率增强
                    img = img.transpose(Image.FLIP_LEFT_RIGHT)

                brightness_factor = rng.uniform(0.9, 1.1)
                enhancer = ImageEnhance.Brightness(img)
                img = enhancer.enhance(brightness_factor)

            # neurotypical (label=4) 不做增强
            # elif label == 4:  # neurotypical
            #     if rng.random() > 0.8:  # 20%概率
            #         img = img.transpose(Image.FLIP_LEFT_RIGHT)
            #     brightness_factor = rng.uniform(0.98, 1.02)
            #     img = ImageEnhance.Brightness(img).enhance(brightness_factor)

            augmented_images.append(img)

        return augmented_images






