class SaveModelEachEpoch(Callback):
    def __init__(self, save_dir, fold_num):
        super(SaveModelEachEpoch, self).__init__()
        self.save_dir = save_dir
        self.fold_num = fold_num

    def on_epoch_end(self, epoch, logs=None):
        # 创建每个epoch的模型保存路径
        epoch_model_path = os.path.join(
            self.save_dir,
            f'fold_{self.fold_num}_epoch_{epoch+1:03d}.h5'
        )
        # 保存模型
        self.model.save(epoch_model_path)
        print(f'Fold {self.fold_num} - Epoch {epoch+1}: 模型已保存至 {epoch_model_path}')


