class SENetLayer(Layer):
    def __init__(self, ratio=16, **kwargs):
        super(SENetLayer, self).__init__(**kwargs)
        self.ratio = ratio

    def build(self, input_shape):
        channel_axis = 1 if K.image_data_format() == "channels_first" else -1
        channel_count = input_shape[channel_axis]

        self.global_avg_pool = GlobalAveragePooling2D()
        self.dense_1 = Dense(channel_count // self.ratio, activation='relu',
                            kernel_regularizer=l2(1e-5), use_bias=False)
        self.dense_2 = Dense(channel_count, activation='sigmoid',
                            kernel_regularizer=l2(1e-5), use_bias=False)
        self.multiply = Multiply()
        super(SENetLayer, self).build(input_shape)

    def call(self, inputs):
        se_feature = self.global_avg_pool(inputs)
        se_feature = self.dense_1(se_feature)
        se_feature = self.dense_2(se_feature)
        x = self.multiply([inputs, se_feature])
        return x

    def get_config(self):
        config = super().get_config()
        config.update({"ratio": self.ratio})
        return config

# ==================== 新增：增强的残差注意力块 ====================
class EnhancedResidualBlock(Layer):
    """结合残差连接和多尺度特征的增强块"""
    def __init__(self, filters, kernel_size=3, use_se=True, **kwargs):
        super(EnhancedResidualBlock, self).__init__(**kwargs)
        self.filters = filters
        self.kernel_size = kernel_size
        self.use_se = use_se

    def build(self, input_shape):
        # 主路径：两个卷积层
        self.conv1 = Conv2D(self.filters, self.kernel_size, padding='same',
                           kernel_regularizer=l2(1e-5))
        self.bn1 = BatchNormalization()

        self.conv2 = Conv2D(self.filters, self.kernel_size, padding='same',
                           kernel_regularizer=l2(1e-5))
        self.bn2 = BatchNormalization()

        # 多尺度特征提取
        self.conv3x3 = Conv2D(self.filters//4, 3, padding='same')
        self.conv5x5 = Conv2D(self.filters//4, 5, padding='same')
        self.conv1x1 = Conv2D(self.filters//2, 1, padding='same')

        # ========== 新增：在这里创建缺失的层 ==========
        # 多尺度特征的BN和激活
        self.bn_ms = BatchNormalization()
        self.activation_ms = Activation('relu')

        # 合并多尺度特征
        self.concat = Concatenate()
        self.add_ms = Add()  # 用于合并多尺度特征

        # 注意力
        if self.use_se:
            self.se = SENetLayer(ratio=16)

        # 快捷连接
        self.shortcut_conv = Conv2D(self.filters, 1, padding='same')
        self.shortcut_bn = BatchNormalization()

        # ========== 新增：残差合并层 ==========
        self.add_residual = Add()
        self.activation_out = Activation('relu')

        super().build(input_shape)

    def call(self, inputs):
        # 主路径
        x = self.conv1(inputs)
        x = self.bn1(x)
        x = Activation('relu')(x)

        x = self.conv2(x)
        x = self.bn2(x)

        # 多尺度特征
        branch1 = self.conv3x3(x)
        branch2 = self.conv5x5(x)
        branch3 = self.conv1x1(x)

        # 合并多尺度特征
        multi_scale = self.concat([branch1, branch2, branch3])
        multi_scale = self.bn_ms(multi_scale)
        multi_scale = self.activation_ms(multi_scale)

        # 与主路径融合 - 使用在build中创建的层
        x = self.add_ms([x, multi_scale])

        # SE注意力
        if self.use_se:
            x = self.se(x)

        # 残差连接
        shortcut = self.shortcut_conv(inputs)
        shortcut = self.shortcut_bn(shortcut)

        # 最终输出 - 使用在build中创建的层
        output = self.add_residual([x, shortcut])
        output = self.activation_out(output)

        return output

    def get_config(self):
        config = super().get_config()
        config.update({
            'filters': self.filters,
            'kernel_size': self.kernel_size,
            'use_se': self.use_se
        })
        return config

# ==================== 新的模型架构 ====================
def build_cnn_model(input_shape=(64, 64, 3), num_classes=5, learning_rate=0.0002):
    """
    增强的ADBrainNet架构
    核心改进：
    1. 多尺度特征提取
    2. 残差连接（避免梯度消失）
    3. 渐进式特征融合
    4. 增强的SE注意力
    """
    model = Sequential()

    # ========== Stage 1: 高分辨率特征提取 ==========
    # 使用大卷积核捕获更大感受野
    model.add(Conv2D(32, (7, 7), strides=2, padding='same',
                     activation='relu', input_shape=input_shape,
                     kernel_regularizer=l2(1e-5)))
    model.add(BatchNormalization())
    model.add(MaxPooling2D((3, 3), strides=2, padding='same'))
    model.add(Dropout(0.1))  # 低层减少dropout

    # ========== Stage 2: 多尺度特征学习 ==========
    # 增强残差块1
    model.add(EnhancedResidualBlock(64, use_se=True))
    model.add(MaxPooling2D((2, 2)))
    model.add(Dropout(0.15))

    # ========== Stage 3: 中级特征抽象 ==========
    model.add(EnhancedResidualBlock(128, use_se=True))
    model.add(MaxPooling2D((2, 2)))
    model.add(Dropout(0.2))

    # ========== Stage 4: 高级特征抽象 ==========
    model.add(EnhancedResidualBlock(256, use_se=True))
    # 这里不用MaxPooling，用平均池化保留更多空间信息
    model.add(AveragePooling2D((2, 2)))
    model.add(Dropout(0.25))

    # ========== Stage 5: 特征精炼 ==========
    model.add(EnhancedResidualBlock(512, use_se=True))
    # 全局平均池化替代Flatten，减少参数防止过拟合
    model.add(GlobalAveragePooling2D())
    model.add(Dropout(0.3))

    # ========== 特征融合层 ==========
    # 使用多个全连接层进行渐进式特征融合
    model.add(Dense(1024, activation='relu', kernel_regularizer=l2(1e-5)))
    model.add(BatchNormalization())
    model.add(Dropout(0.4))

    model.add(Dense(512, activation='relu', kernel_regularizer=l2(1e-5)))
    model.add(BatchNormalization())
    model.add(Dropout(0.35))

    # 添加一个瓶颈层，强制模型学习压缩表示
    model.add(Dense(256, activation='relu', kernel_regularizer=l2(1e-5)))
    model.add(BatchNormalization())
    model.add(Dropout(0.3))

    # 输出层
    model.add(Dense(num_classes, activation='softmax'))

    model.compile(optimizer=optimizers.Adam(learning_rate=learning_rate),
                         loss=losses.categorical_crossentropy,
                         metrics=[metrics.CategoricalAccuracy(), metrics.Precision(), metrics.Recall(),
                                 ])

    return model

